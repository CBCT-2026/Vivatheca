// Writes the words, sources and lengths of every model video for the site:
// - public/videos/videos.js  (window.VT_VIDEOS, read by public/video-embed.js on static model pages)
// - app/videos.ts            (the same data for the app pages and the model library)
// Run after tts.py has made build/<slug>/<lang>/timeline.json for every script.
// Usage: node tools/video/build-embed.mjs
import { readFileSync, readdirSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));
const root = resolve(here, '..', '..');
const data = {};
for (const file of readdirSync(join(here, 'scripts')).filter((f) => f.endsWith('.json')).sort()) {
  const spec = JSON.parse(readFileSync(join(here, 'scripts', file), 'utf8'));
  const entry = { sources: spec.sources };
  for (const lang of ['en', 'ja']) {
    const tl = join(here, 'build', spec.slug, lang, 'timeline.json');
    if (!existsSync(tl)) throw new Error(`${spec.slug} ${lang}: run tts.py first`);
    const { duration } = JSON.parse(readFileSync(tl, 'utf8'));
    if (duration > 45) throw new Error(`${spec.slug} ${lang}: ${duration} s is over 45 s`);
    entry[lang] = {
      title: spec[lang].title,
      seconds: Math.ceil(duration),
      lines: spec[lang].paragraphs.flatMap((p) => p.sentences.map((s) => ({ text: s.text, cite: s.cite || [] }))),
    };
  }
  data[spec.slug] = entry;
}

const json = JSON.stringify(data, null, 1);
mkdirSync(join(root, 'public/videos'), { recursive: true });
writeFileSync(join(root, 'public/videos/videos.js'),
  `// Generated by tools/video/build-embed.mjs from tools/video/scripts/*.json. Do not edit by hand.\nwindow.VT_VIDEOS = ${json};\n`);
writeFileSync(join(root, 'app/videos.ts'),
  `// Generated by tools/video/build-embed.mjs from tools/video/scripts/*.json. Do not edit by hand.\n` +
  `// One narrated video (at most 45 seconds) per model in the library, in English and Japanese.\n` +
  `export type VideoLine = { text: string; cite: number[] };\n` +
  `export type VideoLang = { title: string; seconds: number; lines: VideoLine[] };\n` +
  `export type ModelVideo = { sources: string[]; en: VideoLang; ja: VideoLang };\n\n` +
  `export const videos: Record<string, ModelVideo> = ${json};\n\n` +
  `export const videoFiles = (slug: string, lang: 'en' | 'ja') => ({\n` +
  `  mp4: \`/videos/\${slug}/\${slug}-\${lang}.mp4\`,\n  vtt: \`/videos/\${slug}/\${slug}-\${lang}.vtt\`,\n  poster: \`/videos/\${slug}/poster-\${lang}.jpg\`,\n});\n`);
console.log(`wrote ${Object.keys(data).length} videos`);
