"""Build public/dentigerous-cyst/index.html and vi.js from page-src.html.

Usage: python3 gen.py page-src.html ../../public/dentigerous-cyst

- {漢字|かな} becomes <ruby> furigana (as tools/cracked-tooth/gen.py).
- Each lang="vi" element must directly follow a lang="en" element with the same tag. The Vietnamese is
  taken out of the HTML and written to vi.js as English innerHTML -> Vietnamese (window.VT_VI_PAGE.html),
  which /inline-vi.js swaps in when the page is in Vietnamese. So English and Vietnamese sit side by side
  in the source, and the served page stays English + Japanese like the other static model pages.
"""
import json
import os
import re
import sys

src, out = sys.argv[1], sys.argv[2]
s = open(src, encoding='utf-8').read()
s = re.sub(r'\{([^{}|]+)\|([^{}|]+)\}', r'<ruby>\1<rp aria-hidden="true">(</rp><rt aria-hidden="true">\2</rt><rp aria-hidden="true">)</rp></ruby>', s)


def element_end(s, start, tag):
    """Index just after the closing tag of the element whose opening tag starts at `start`."""
    depth, i = 0, start
    pat = re.compile(r'<(/?)' + tag + r'(?=[\s>])[^>]*>')
    for m in pat.finditer(s, start):
        depth += -1 if m.group(1) else 1
        if depth == 0:
            return m.end()
    raise ValueError('unclosed <%s> at %d' % (tag, start))


def inner(el):
    return el[el.index('>') + 1:el.rindex('<')].strip()


vi = {}
open_vi = re.compile(r'<(\w+)\s[^>]*lang="vi"[^>]*>')
while True:
    m = open_vi.search(s)
    if not m:
        break
    tag = m.group(1)
    vend = element_end(s, m.start(), tag)
    # the English twin ends right before (whitespace allowed)
    before = s[:m.start()].rstrip()
    ens = [e for e in re.finditer(r'<' + tag + r'\s[^>]*lang="en"[^>]*>', before)]
    en = None
    for e in reversed(ens):
        if element_end(s, e.start(), tag) == len(before):
            en = e
            break
    if en is None:
        raise SystemExit('lang="vi" element without an English twin just before it: ' + s[m.start():m.start() + 80])
    vi[inner(s[en.start():len(before)])] = inner(s[m.start():vend])
    s = s[:len(before)] + s[vend:]

title = re.search(r'<title>(.*?)</title>', s).group(1)
os.makedirs(out, exist_ok=True)
open(os.path.join(out, 'index.html'), 'w', encoding='utf-8').write(s)
page = {'title': 'Nang thân răng của răng cối lớn thứ ba hàm dưới chưa mọc, so với túi răng bình thường | Vivatheca',
        'description': 'Mô hình 3D tương tác của một răng khôn hàm dưới chưa mọc với túi răng bình thường, và cùng răng đó có nang thân răng. Cắt mở để so sánh.',
        'html': vi}
open(os.path.join(out, 'vi.js'), 'w', encoding='utf-8').write(
    '// Vietnamese for /dentigerous-cyst/ (unreviewed AI draft; English prevails). Generated by tools/cyst/gen.py from\n'
    '// page-src.html: edit the source, not this file. Used by /inline-vi.js.\n'
    'window.VT_VI_PAGE = ' + json.dumps(page, ensure_ascii=False, indent=1) + ';\n')
print(len(vi), 'Vietnamese strings;', title)
