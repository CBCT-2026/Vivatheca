"""Build an options page (index.html and vi.js) from its page-src.html.

Usage: python3 tools/options/gen.py tools/options/<model>/page-src.html public/<model-page>/options

Same rules as tools/wisdom-options/gen.py:
- {漢字|かな} becomes <ruby> furigana.
- Each lang="vi" element must directly follow a lang="en" element with the same tag. The Vietnamese is taken
  out of the HTML and written to vi.js (window.VT_VI_PAGE.html: English innerHTML -> Vietnamese), which
  /inline-vi.js swaps in when the page is in Vietnamese; the served page stays English + Japanese.
- The Vietnamese <title> and description come from <meta name="vt-vi-title"> and <meta name="vt-vi-description">
  in the source, which are removed from the output.
"""
import json
import os
import re
import sys

src, out = sys.argv[1], sys.argv[2]
s = open(src, encoding='utf-8').read()
vi_title = re.search(r'<meta name="vt-vi-title" content="([^"]*)">\n?', s)
vi_desc = re.search(r'<meta name="vt-vi-description" content="([^"]*)">\n?', s)
if not vi_title or not vi_desc:
    raise SystemExit('page-src.html needs <meta name="vt-vi-title"> and <meta name="vt-vi-description">')
s = s.replace(vi_title.group(0), '').replace(vi_desc.group(0), '')
s = re.sub(r'\{([^{}|]+)\|([^{}|]+)\}', r'<ruby>\1<rp aria-hidden="true">(</rp><rt aria-hidden="true">\2</rt><rp aria-hidden="true">)</rp></ruby>', s)


def element_end(s, start, tag):
    depth, i = 0, start
    pat = re.compile(r'<(/?)' + tag + r'(?=[\s>])[^>]*>')
    for m in pat.finditer(s, start):
        depth += -1 if m.group(1) else 1
        if depth == 0:
            return m.end()
    raise ValueError('unclosed <%s> at %d' % (tag, start))


def inner(el):
    return el[el.index('>') + 1:el.rindex('<')].strip()


vi = {}
open_vi = re.compile(r'<(\w+)\s[^>]*lang="vi"[^>]*>')
while True:
    m = open_vi.search(s)
    if not m:
        break
    tag = m.group(1)
    vend = element_end(s, m.start(), tag)
    before = s[:m.start()].rstrip()
    en = None
    for e in reversed(list(re.finditer(r'<' + tag + r'\s[^>]*lang="en"[^>]*>', before))):
        if element_end(s, e.start(), tag) == len(before):
            en = e
            break
    if en is None:
        raise SystemExit('lang="vi" element without an English twin just before it: ' + s[m.start():m.start() + 120])
    vi[inner(s[en.start():len(before)])] = inner(s[m.start():vend])
    s = s[:len(before)] + s[vend:]

title = re.search(r'<title>(.*?)</title>', s).group(1)
page_path = '/' + out.split('public/', 1)[-1].strip('/') + '/'
os.makedirs(out, exist_ok=True)
open(os.path.join(out, 'index.html'), 'w', encoding='utf-8').write(s)
page = {'title': vi_title.group(1), 'description': vi_desc.group(1), 'html': vi}
open(os.path.join(out, 'vi.js'), 'w', encoding='utf-8').write(
    '// Vietnamese for ' + page_path + ' (unreviewed AI draft; English prevails). Generated by tools/options/gen.py from\n'
    '// ' + os.path.relpath(src) + ': edit the source, not this file. Used by /inline-vi.js.\n'
    'window.VT_VI_PAGE = ' + json.dumps(page, ensure_ascii=False, indent=1) + ';\n')
print(len(vi), 'Vietnamese strings;', title)
